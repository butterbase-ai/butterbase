import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { generateLlmsFullTxt, generateLlmsTxt, localizeSidebar, resolveSidebarItems, type Sidebar } from './llms-generator';
import { changelog } from '../data/changelog';
import { changelogJa } from '../data/changelog-ja';

let docs: string;
function page(slug: string, content: string) {
  const path = join(docs, slug);
  mkdirSync(join(path, '..'), { recursive: true });
  writeFileSync(path, content);
}
const sidebar: Sidebar = [
  { label: 'Start', translations: { ja: 'はじめに' }, items: [
    { label: 'Quickstart', slug: 'quickstart', translations: { ja: 'クイックスタート' } },
    { label: 'Missing translation', slug: 'english-only' },
  ] },
  { label: 'API', translations: { ja: 'APIリファレンス' }, autogenerate: { directory: 'api' } },
  { label: 'Untranslated group', items: [{ label: 'Other', slug: 'other' }] },
];
beforeEach(() => {
  docs = mkdtempSync(join(tmpdir(), 'butterbase-docs-locale-'));
  page('quickstart.mdx', '---\ntitle: Quickstart\n---\nEnglish quickstart.');
  page('english-only.md', '---\ntitle: English only\n---\nEnglish fallback.');
  page('other.md', 'Other page.');
  page('api/data.md', '---\ntitle: Data API\n---\nEnglish API.');
  page('ja/quickstart.mdx', '---\ntitle: クイックスタート\n---\n日本語の開始手順。');
  page('ja/api/data.md', '---\ntitle: データAPI\n---\n日本語のAPI。');
  page('ja/api/_hidden.md', 'Hidden source.');
  page('ja/api/draft.md', '---\ntitle: 下書き\ndraft: true\n---\nDraft source.');
});
afterEach(() => rmSync(docs, { recursive: true, force: true }));

describe('LLM documentation language boundaries', () => {
  it('keeps the default English URLs and content', () => {
    const items = resolveSidebarItems(sidebar, docs);
    const index = generateLlmsTxt(items, 'https://docs.example');
    expect(index).toContain('https://docs.example/quickstart/');
    expect(index).not.toContain('/ja/');
    expect(generateLlmsFullTxt(items, 'https://docs.example')).toContain('English quickstart.');
  });
  it('includes translated MDX and API pages with localized labels', () => {
    const items = resolveSidebarItems(localizeSidebar(sidebar, docs, 'ja'), docs);
    expect(items.map(({ slug }) => slug)).toEqual(['ja/quickstart', 'ja/api/data']);
    const index = generateLlmsTxt(items, 'https://docs.example', 'ja');
    expect(index).toContain('## はじめに');
    expect(index).toContain('クイックスタート: https://docs.example/ja/quickstart/');
    expect(index).toContain('データAPI: https://docs.example/ja/api/data/');
    const full = generateLlmsFullTxt(items, 'https://docs.example', 'ja');
    expect(full).toContain('日本語の開始手順。');
    expect(full).toContain('日本語のAPI。');
    expect(full).not.toContain('English fallback.');
    expect(full).not.toContain('Draft source.');
    expect(full).not.toContain('Hidden source.');
  });
  it('does not label English fallback or missing groups as translated', () => {
    expect(localizeSidebar(sidebar, docs, 'fr')).toEqual([]);
    const localized = localizeSidebar(sidebar, docs, 'ja');
    expect(localized).toHaveLength(2);
    expect(JSON.stringify(localized)).not.toContain('english-only');
    expect(JSON.stringify(localized)).not.toContain('other');
  });
  it.each(['md', 'mdx'])('excludes explicit %s drafts, including YAML comments', extension => {
    page(`ja/private.${extension}`, '---\ntitle: 未公開\ndraft: true # unpublished\n---\nDo not publish this.');
    const entries: Sidebar = [{ label: 'Start', items: [{ label: 'Private', slug: 'private' }] }];
    const items = resolveSidebarItems(localizeSidebar(entries, docs, 'ja'), docs);
    expect(items).toEqual([]);
    expect(generateLlmsFullTxt(items, 'https://docs.example', 'ja')).not.toContain('Do not publish this.');
  });
  it('uses YAML booleans and titles for autogenerated pages', () => {
    page('ja/api/hidden.md', '---\ntitle: "未公開: 検証"\ndraft: true # unpublished\n---\nPrivate.');
    page('ja/api/public.md', '---\ntitle: "公開: API"\ndraft: false # published\n---\nPublic.');
    const items = resolveSidebarItems(localizeSidebar(sidebar, docs, 'ja'), docs);
    expect(items.map(({ slug }) => slug)).not.toContain('ja/api/hidden');
    expect(items.find(({ slug }) => slug === 'ja/api/public')?.label).toBe('公開: API');
  });
  it('fails the build when a declared source page is missing', () => {
    expect(() => resolveSidebarItems([{ label: 'Required', items: [{ label: 'Absent', slug: 'absent' }] }], docs)).toThrow('No source file found');
  });
});

it('has a translation for every published changelog item', () => {
  expect(Object.keys(changelogJa).sort()).toEqual(changelog.map(({ title }) => title).sort());
  for (const item of changelog) {
    expect(changelogJa[item.title].title.trim()).not.toBe('');
    expect(changelogJa[item.title].description).toMatch(/[\u3040-\u9fff]/);
  }
});
