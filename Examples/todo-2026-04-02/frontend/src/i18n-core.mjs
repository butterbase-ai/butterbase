const storageKey = 'butterbase-example-language';
let language = 'en';
const listeners = new Set();
try { if (globalThis.localStorage?.getItem(storageKey) === 'ja') language = 'ja'; } catch {}
export function getLocale() { return language; }
export function subscribe(listener) { listeners.add(listener); return () => listeners.delete(listener); }
export function setLocale(value) {
  language = value === 'ja' ? 'ja' : 'en';
  try { globalThis.localStorage?.setItem(storageKey, language); } catch {}
  for (const listener of listeners) listener();
}
export function text(source) { return language === 'ja' && Object.hasOwn(translations, source) ? translations[source] : source; }
export function formatDate(value) { return new Date(value).toLocaleString(language === 'ja' ? 'ja-JP' : undefined); }
